def _swap(k):
    """Смена рта в петле без двух ртов: k 0 → 1; первый рот закрывается к
    k = 0,5, второй раскрывается после. (первый, второй) — доли 0..1."""
    return (lambda t: max(0.0, 1.0 - 2.0 * k(t))), (lambda t: max(0.0, 2.0 * k(t) - 1.0))


