def tickle_keys(d):
    """«Щекотка» лицом смеха (лист «Смех»): серпы ◠, «D», бровки наклоном,
    подушечки щёк; «ха» волнами по длине клипа."""
    B = lambda **kw: ('laugh_big', kw)
    keys = [(2, 'calm'), (14, ('laugh', {'arc': 0.5, 'h_laugh': 0.1, 'brow': 0.4})), (28, 'laugh', EO)]
    f, i = 40, 0
    while f < d - 40:
        keys.append((f, B(h_laugh=0.95 - 0.05 * (i % 3), blift=16.0) if i % 2 == 0 else B(h_laugh=0.55, blift=6.0,
                                                                                            chin=-2.0)))
        f += 12
        i += 1
    return keys + [(d - 30, ('laugh', {'h_laugh': 0.0, 'p_lip': 0.0, 'p_smile_wide': 1.0, 'brow': 0.2})),
                   (d - 16, ('smile', {'p_smile': 0.5})), (d - 4, 'calm')]


