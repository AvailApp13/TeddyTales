def sleepy_loop():
    """«Покой: сонный» — тяжёлые веки, медленные моргания-дрёмы, зевок «U»."""
    nod = lambda t: rr.mbump(t, 300, 70)
    slow = lambda t: rr.mbump(t, 150, 38) + rr.mbump(t, 440, 44)
    yw = lambda t: rr.mbump(t, 540, 72)
    ye = lambda t: min(1.0, yw(t) / 0.5)
    close = lambda t: min(1.0, slow(t) + ye(t))
    ex = {'top': 1.0, 'tilt': -6.0, 'lidcap': 1.0, 'p_sleepy': 1.0, 'shut': 1.0, 'stilt': 2.5, 'sbold': 1.0, 'sarch': -3.0,
          'p_yawnlip': 1.0, 'h_gape': 1.0, 'w_gape': 1.0, 'chin': -12.0, 'cheek': 2.5, 'cheek_sy': 0.04, 'bup': -1.5}
    mod = {'top': lambda t: 0.6 + 0.28 * nod(t), 'tilt': lambda t: (0.6 + 0.4 * nod(t)) * (1 - close(t)),
           'lidcap': lambda t: 1 - close(t), 'p_sleepy': lambda t: (0.6 + 0.4 * nod(t)) * (1 - min(1.0, yw(t) / 0.3)),
           'shut': close, 'stilt': lambda t: slow(t) * (1 - ye(t)), 'sbold': lambda t: 0.25 * slow(t) + 0.75 * yw(t),
           'sarch': yw, 'cheek': yw, 'cheek_sy': yw, 'bup': yw, 'chin': yw,
           'p_yawnlip': lambda t: min(1.0, yw(t) / 0.3), 'h_gape': lambda t: max(0.0, (yw(t) - 0.25) / 0.75),
           'w_gape': lambda t: min(1.0, yw(t) / 0.6)}
    return ex, mod


def hungry_loop():
    """«Покой: голод»: причмокивание — щёлочкой жевания (рот «munch»)."""
    smack = lambda t: 0.4 * rr.mbump(t, 470, 22) + 0.3 * rr.mbump(t, 520, 20)
