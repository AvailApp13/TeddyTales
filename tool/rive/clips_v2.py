def calm_trait_v2():
    """Петля «Спокойный» по листу «Задумчивость, уют», 12 с: задумчиво
    смотрит в сторону и вниз, потом с уютом к зрителю; вздох, кивок."""
    mh, mb = rr.mhold, rr.mbump
    away = lambda t: mh(t, 116, 366, 60)
    drift = lambda t: mb(t, 270, 50)
    nod = lambda t: mb(t, 540, 90)
    sigh = lambda t: mb(t, 500, 45)
    sp = {
        ('face', Y): lambda t: -13.0 * away(t) + 2.0 * drift(t),
        ('face', X): lambda t: -3.0 - 1.0 * away(t) - 2.0 * nod(t),
        ('head', R): lambda t: 0.045 * away(t - 6) - 0.008 * drift(t) + 0.012 * nod(t),
        ('hood2', R): lambda t: 0.04 * away(t - 14) + 0.03 * nod(t - 20),
        ('chest', R): lambda t: 0.01 * away(t - 10),
        ('breath', SY): lambda t: 0.035 * sigh(t),
        ('ear_l1', R): lambda t: 0.05 + 0.02 * away(t - 12),
        ('ear_r1', R): lambda t: -0.05 - 0.02 * away(t - 12),
    }
    eye = lambda t: mh(t, 104, 356, 12)
    g = lambda t: (eye(t) * (1 - 0.17 * drift(t)) - 0.2 * mh(t, 56, 90, 4) + 0.2 * mh(t, 496, 530, 4)
                   - 0.17 * mh(t, 616, 650, 4))
    gv = lambda t: eye(t) * (1 - 0.33 * drift(t))
    return fv.loop_face(sp, 'pensive', {'gx': g, 'gy': gv})


