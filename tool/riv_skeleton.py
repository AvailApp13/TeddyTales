#!/usr/bin/env python3
"""Скелет мишки: кости, привязка вершин, матрицы.

Зачем скелет, если сетка уже была. Сетка двигает вершины поодиночке, и
каждая деталь живёт своей дорожкой: кофта раздувается по своим ключам,
голова едет по своим. Стоит им разойтись на десяток пикселей — по плечу
идёт засветка, на стыке видна ступенька. Лечить это приходилось, урезая
движение, то есть отнимая у мишки жизнь.

Скелет снимает вопрос по построению. Есть одна цепочка костей от пола до
шеи; вершины кофты и ног привязаны к ней с плавными весами, а голова висит
на кости шеи. Дышит позвоночник — вместе с ним едет всё остальное, потому
что всё остальное на нём и держится. Разойтись не может.

Кость в Rive смотрит вдоль своей локальной оси X, поэтому цепочка,
поставленная вертикально, развёрнута на минус девяносто градусов: ось X
кости указывает вверх по экрану. Отсюда матрица вида

    [xx yx tx]   [0  1  cx]
    [xy yy ty] = [-1 0  cy]

и локальные координаты точки внутри кости: x вдоль кости (вверх), y поперёк
(вправо).

Деформация вершины в рантайме считается так:

    world = Σ w_i · (Bone_i.world · Tendon_i.inverseBind) · (Skin.world · v)

В покое Bone.world равна Tendon.bind, произведение вырождается в единицу, и
вершина стоит там, куда её ставит Skin.world. Поэтому bind-матрицы тендонов
— это в точности мировые матрицы костей в покое, а Skin.world — посадка
детали на сцену.
"""

from __future__ import annotations

import math

STAGE_CENTRE = 540.0
STAGE_BASELINE = 1350.0
"""Точка опоры: пол под ступнями мишки, середина по ширине."""

# Цепочка снизу вверх: имя и длина кости в пикселях сцены. Суставы
# расставлены по силуэту — колени, пояс, живот, плечи, шея.
CHAIN = (
    ('root', 195.0),    # пол -> колени
    ('hips', 175.0),    # колени -> низ кофты
    ('spine', 190.0),   # низ кофты -> живот
    ('chest', 170.0),   # живот -> плечи
    ('neck', 100.0),    # плечи -> основание головы
)

NAMES = [name for name, _ in CHAIN]


def joints() -> dict[str, float]:
    """Мировая y начала каждой кости. Цепочка идёт вверх, значит y убывает."""
    out: dict[str, float] = {}
    y = STAGE_BASELINE
    for name, length in CHAIN:
        out[name] = y
        y -= length
    out['tip'] = y
    return out


JOINTS = joints()

CENTRES = {name: JOINTS[name] - length / 2 for name, length in CHAIN}
"""Середина каждой кости: по ней распределяются веса вершин."""


def bone_bind(name: str) -> tuple[float, ...]:
    """Мировая матрица кости в покое: (xx, yx, xy, yy, tx, ty).

    Все кости цепочки смотрят вверх и стоят на одной вертикали, так что
    отличаются только сдвигом по y.
    """
    return (0.0, 1.0, -1.0, 0.0, STAGE_CENTRE, JOINTS[name])


def skin_bind(centre_x: float, centre_y: float,
              scale: float) -> tuple[float, ...]:
    """Матрица посадки детали: пиксели картинки -> сцена."""
    return (scale, 0.0, 0.0, scale, centre_x, centre_y)


def to_bone_space(name: str, x: float, y: float) -> tuple[float, float]:
    """Точку сцены — в локальные координаты кости.

    Нужно, чтобы повесить голову на шею: узел задаётся в системе родителя.
    """
    return (JOINTS[name] - y, x - STAGE_CENTRE)


HEAD_UPRIGHT = math.pi / 2
"""Разворот для узла, висящего на кости.

Кость лежит на боку (ось X вверх), и всё, что на ней висит, наследует этот
разворот. Плюс девяносто градусов возвращают голову в вертикальное
положение.
"""


def influences(world_y: float, bones: list[str]) -> list[tuple[int, int]]:
    """Кости, которые тянут вершину, и их веса 0…255.

    Вес распределяется между двумя ближайшими по высоте костями. Двух
    достаточно: цепочка одномерная, третья кость находится дальше половины
    своего пролёта и её вклад всё равно обнулился бы.

    Возвращает пары (номер тендона, вес). Номер — это позиция кости в
    `bones` плюс один: нулевой слот в рантайме занят единичной матрицей
    самого скина.
    """
    ladder = sorted(((CENTRES[name], index + 1)
                     for index, name in enumerate(bones)),
                    key=lambda item: item[0])

    if world_y <= ladder[0][0]:
        return [(ladder[0][1], 255)]
    if world_y >= ladder[-1][0]:
        return [(ladder[-1][1], 255)]

    for (y_low, low), (y_high, high) in zip(ladder, ladder[1:]):
        if y_low <= world_y <= y_high:
            span = y_high - y_low
            share = 0.0 if span == 0 else (world_y - y_low) / span
            # Сглаживаем переход: линейный вес даёт излом на суставе,
            # косинусный — плавную волну вдоль тела.
            share = (1 - math.cos(math.pi * share)) / 2
            upper = int(round(255 * (1 - share)))
            return [(low, upper), (high, 255 - upper)]

    raise SystemExit(f'Вершина y={world_y} не легла ни на одну кость')


def pack(pairs: list[tuple[int, int]]) -> tuple[int, int]:
    """Упаковывает привязку в пару uint32: индексы и веса, по байту на кость."""
    indices = values = 0
    for slot, (index, weight) in enumerate(pairs[:4]):
        indices |= (index & 0xFF) << (slot * 8)
        values |= (weight & 0xFF) << (slot * 8)
    return indices, values
