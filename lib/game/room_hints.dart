/// Подсказки пустых мест в комнате: «сюда можно поставить кроватку».
///
/// ## Зачем
///
/// Комната открыта с первого дня (решение заказчика 17.09), и в первый день
/// она пустая: стены, пол и мишка. Человек видит пустоту и не знает, что с
/// ней делать, — а у него в инвентаре уже лежат двенадцать бесплатных вещей
/// (КП 10.8), которые он не доставал.
///
/// Подсказка закрывает обе дыры сразу: показывает, что комнату вообще можно
/// обставлять, и ведёт к первой покупке. Сначала предлагается поставить то,
/// что уже есть, — бесплатное действие с мгновенным результатом; когда своё
/// кончится, на тех же местах появится то, что нужно купить. Человек
/// проходит путь «поставил → понравилось → хочу ещё» сам, без обучалки.
///
/// ## Почему логика живёт отдельно от разметки
///
/// Выбор подсказок — это правило игры, а не рисование: какие места важнее,
/// сколько показывать разом, что идёт раньше — своё или покупное. Такие
/// правила должны проверяться тестами без запуска интерфейса.
library;

import '../bear/bear_rig_spec.dart';
import 'room_layout.dart';
import 'shop_items.dart';

/// Одно подсвеченное место.
class RoomHint {
  const RoomHint({required this.placement, required this.owned});

  /// Где и какого размера — из размерной сетки комнаты.
  final RoomPlacement placement;

  /// Предмет уже куплен: тап просто поставит его, платить не нужно.
  final bool owned;

  String get id => placement.id;
}

/// Сколько подсказок показывать разом.
///
/// Три — не круглое число, а предел читаемости: подсветить все пустые места
/// значит закрасить комнату пунктиром и спрятать за ним мишку. Три
/// подсказки видно с одного взгляда, и каждая остаётся приглашением, а не
/// списком дел.
const int maxRoomHints = 3;

/// Ширина места в долях ширины сцены.
///
/// Размерная сетка меряет предметы в модулях (модуль — рост мишки), а модуль
/// задан долей ВЫСОТЫ сцены. Чтобы понять, налезают ли две рамки друг на
/// друга, нужна доля ШИРИНЫ — отсюда деление на пропорции сцены.
///
/// Пропорции взяты приблизительно: сцена на главном экране примерно вдвое
/// выше своей ширины. Точность здесь и не нужна — от неё зависит только то,
/// сочтём ли мы две рамки соседями, а запас в четверть модуля спокойно
/// покрывает разницу между телефоном и планшетом.
const double _sceneAspect = 0.5;
const double _bearModule = 0.22;

/// Верхняя полоса сцены, куда подсказки не ставятся: там пузырь с репликой
/// и кнопка ухода.
const double _topReserved = 0.2;

double _widthFraction(RoomPlacement p) => p.w * _bearModule / _sceneAspect;

/// Пересекаются ли места по горизонтали.
///
/// Настенное и напольное не спорят: одно висит, другое стоит на полу.
bool _overlap(RoomPlacement a, RoomPlacement b) {
  if (a.onWall != b.onWall) return false;

  final ha = _widthFraction(a) / 2;
  final hb = _widthFraction(b) / 2;
  return (a.fx - b.fx).abs() < ha + hb;
}

/// Какие места подсветить при текущем состоянии комнаты.
///
/// Порядок осмысленный, а не случайный:
/// 1. Сначала то, что уже куплено, — это бесплатно и работает сразу.
/// 2. Потом крупное вперёд мелкого. Комнату делает кроватка, а не уточка:
///    подсветить три мелочи у плинтуса — значит показать, что обставлять
///    нечем. Сортировка по цене, к которой напрашивается рука, даёт ровно
///    это: самое дешёвое в каталоге — самое мелкое.
/// 3. Рамки, налезающие на уже выбранные, пропускаются: две подписи одна
///    поверх другой не читаются ни как приглашение, ни как что-либо ещё.
///
/// Обои и полы сюда не попадают: они не «стоят на месте», а всегда покрывают
/// комнату целиком, и пустого места под них не бывает.
List<RoomHint> roomHints({
  required Set<String> placed,
  required Set<String> owned,
  required BearStage stage,
  int limit = maxRoomHints,
}) {
  final candidates = <RoomHint>[];

  for (final placement in roomLayout) {
    if (placed.contains(placement.id)) continue;

    final item = ItemCatalog.byId(placement.id);
    if (item.kind == ItemKind.wallpaper || item.kind == ItemKind.floor) {
      continue;
    }
    // Верх сцены занят: слева пузырь с репликой питомца (КП 3.4), справа
    // кнопка «Что будем делать?». Гирлянда висит как раз там, и её рамка
    // перечёркивала и то и другое. Место под самым потолком подсветить
    // некуда — предложим его, когда под ним встанет что-то ещё.
    if (placement.onWall && placement.wallFy! < _topReserved) continue;
    // Не предлагаем малышу то, что ему пока не по возрасту: письменный стол
    // новорождённому — такая же нелепость в комнате, как и в витрине.
    if (!item.suitsAt(stage)) continue;

    candidates.add(
      RoomHint(placement: placement, owned: owned.contains(placement.id)),
    );
  }

  double area(RoomHint h) => h.placement.w * h.placement.h;

  candidates.sort((a, b) {
    if (a.owned != b.owned) return a.owned ? -1 : 1;
    final byArea = area(b).compareTo(area(a));
    if (byArea != 0) return byArea;
    return ItemCatalog.byId(a.id).price.compareTo(ItemCatalog.byId(b.id).price);
  });

  // Места уже стоящих вещей: подсказка не должна их накрывать. Ковёр шире
  // половины комнаты, и его рамка ложилась поверх кроватки — та переставала
  // нажиматься, потому что тап доставался подсказке. Стоящая вещь важнее
  // приглашения: по ней человек меняет обстановку.
  final taken = [
    for (final p in roomLayout)
      if (placed.contains(p.id)) p,
  ];

  final chosen = <RoomHint>[];
  for (final hint in candidates) {
    if (chosen.length >= limit) break;
    final clashes =
        chosen.any((c) => _overlap(c.placement, hint.placement)) ||
        taken.any((t) => _overlap(t, hint.placement));
    if (clashes) continue;
    chosen.add(hint);
  }

  return chosen;
}
