/// Где у вещи тело, а где пусто: сетка по прямоугольнику вещи.
///
/// Заказчик 09.10 (проверка интерьера): нажатие по комоду, ковру и полу у
/// ног мишки открывало кресло. Прямоугольник слоя кресла вместе с тенью
/// накрывал полкомнаты и забирал касание себе. Теперь нажимается только
/// сама вещь: прозрачное и тень пропускают касание к тому, что под ними.
///
/// Сетки считаются заранее, по тем же картинкам, что видны в комнате:
/// у 3D-слоёв — `tool/nursery3d/items.py` (по самой вещи, без тени), у
/// картинок магазина — `tool/item_shapes.py`.
library;

class HitMask {
  const HitMask(this.hex);

  /// Клеток по каждой стороне.
  static const int side = 32;

  /// Сетка построчно сверху вниз, по биту на клетку, старший бит — левый.
  final String hex;

  /// Попадает ли точка в вещь. [fx], [fy] — доли ширины и высоты
  /// прямоугольника вещи.
  bool contains(double fx, double fy) {
    if (fx < 0 || fy < 0 || fx >= 1 || fy >= 1) return false;
    final i = (fy * side).floor() * side + (fx * side).floor();
    final at = 2 * (i >> 3);
    final byte = int.parse(hex.substring(at, at + 2), radix: 16);
    return byte & (0x80 >> (i & 7)) != 0;
  }
}
