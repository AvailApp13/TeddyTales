/// Возрастная развилка контента.
///
/// Уточнение владельца продукта (см. `docs/tz-app.md`, «Аудитория»):
/// основная аудитория — взрослые 18+, дети — желанный, но вторичный охват.
/// Поэтому режимов два, и взрослый — основной: он предлагается первым.
///
/// Возраст спрашивается один раз при первом входе в раздел игр и влияет
/// только на набор контента. Никуда не отправляется и нигде, кроме профиля,
/// не хранится.
library;

enum Audience {
  /// До [Audience.adultFrom] лет: обучающие категории из КП 9 —
  /// цвета и формы, счёт, окружающий мир.
  kids,

  /// Головоломки для взрослых: пазлы с мишками, 2048, память.
  adult;

  /// С какого возраста включается взрослый набор.
  ///
  /// Порог осознанно низкий: «взрослые» головоломки прекрасно заходят
  /// подросткам, а вот взрослому увидеть «где красный?» — обидно.
  static const int adultFrom = 12;

  static Audience forAge(int age) => age >= adultFrom ? adult : kids;
}
