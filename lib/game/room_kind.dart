/// Комнаты, между которыми переключается сцена.
///
/// По КП 10.1 комната одна — детская. Кухня и ванная появились решением
/// заказчика (17.09): фоны заказаны серией, в одном стиле и с одним светом,
/// потому что отдельный заказ через полгода означает другого художника и
/// переделку первой комнаты под новые две.
///
/// **Механик за ними пока нет.** Кормление по КП 8 и мытьё по КП 6.4
/// происходят на главном экране, а не на кухне и не в ванной. Сейчас это
/// смена обстановки: игрок переносит мишку туда, где ему нравится, и видит,
/// что мир не заканчивается одной комнатой. Когда (и если) механики появятся,
/// место для них уже готово.
library;

enum RoomKind {
  nursery('assets/rooms/nursery.png'),
  kitchen('assets/rooms/kitchen.png'),
  bath('assets/rooms/bath.png');

  const RoomKind(this.asset);

  /// Фон комнаты. Черновая генерация от 17.09 — дизайнер перерисует её
  /// заново, но композиция, свет и высота горизонта останутся теми же:
  /// под них размечены места предметов (`docs/room-design-v1.md`).
  final String asset;
}
