/// Правила имени питомца (КП 2.3).
///
/// Имя — первое, что человек даёт мишке, и единственное место в игре, куда
/// он пишет свой текст. Поэтому здесь две разные задачи, и их нельзя путать.
///
/// **Форма** — длина, пробелы, допустимые знаки. Проверяется на устройстве
/// мгновенно, пока человек печатает: ошибку видно сразу, а не после
/// отправки.
///
/// **Содержание** — брань и запрещённые слова. Проверяется на сервере
/// (`name_blocklist`, КП 15.6). Список слов не место в приложении: он
/// правится модератором из панели, а клиент со старым списком пропустил бы
/// то, что уже запретили. Здесь остаётся только грубое сито для очевидного,
/// чтобы не гонять заведомо плохое по сети.
library;

/// Что не так с именем. `null` — имя годится.
enum PetNameError {
  /// Пусто или одни пробелы.
  empty,

  /// Короче двух знаков (КП 2.3).
  tooShort,

  /// Длиннее пятнадцати знаков (КП 2.3).
  tooLong,

  /// Знаки, которых в имени быть не должно: цифры, скобки, решётки.
  badCharacters,

  /// Сито грубых слов на устройстве.
  ///
  /// Отдельно от [PetNameError.rejected]: здесь решение принял телефон, там —
  /// сервер. Для человека разницы нет, для нас есть: локальное сито
  /// заведомо неполное.
  blocked,

  /// Сервер отказал: слово нашлось в списке модератора.
  rejected,

  /// До сервера не достучались. Не про имя вовсе, но человеку сообщить
  /// надо — иначе он будет думать, что дело в имени, и перебирать слова.
  network,
}

/// Наименьшая и наибольшая длина имени (КП 2.3).
const int petNameMinLength = 2;
const int petNameMaxLength = 15;

/// Приводит введённое к виду, в котором имя хранится.
///
/// Пробелы по краям срезаются, несколько подряд схлопываются в один: «  Тед
///   ди » и «Тед ди» — одно и то же имя, и хранить их как разные значит
/// пустить в игру двух «одинаковых» мишек с разными записями в базе.
String normalizePetName(String raw) =>
    raw.trim().replaceAll(RegExp(r'\s+'), ' ');

/// Проверка формы имени. Быстрая, на устройстве, без сети.
PetNameError? checkPetName(String raw) {
  final name = normalizePetName(raw);

  if (name.isEmpty) return PetNameError.empty;
  // Считаем по символам, а не по кодовым единицам: в китайском имени из двух
  // иероглифов `length` строки даёт два, а вот эмодзи — суррогатную пару, и
  // «🐻🐻» прошло бы как четыре знака.
  final length = name.runes.length;
  if (length < petNameMinLength) return PetNameError.tooShort;
  if (length > petNameMaxLength) return PetNameError.tooLong;

  // Разрешены буквы любого алфавита, пробел, дефис и апостроф: этого хватает
  // на русские, английские и китайские имена, на «Мишка-Топтыжка» и на
  // «O'Teddy». Цифры и знаки препинания запрещены — не потому, что вредны,
  // а потому, что имя с решёткой и скобками читается как ник с форума, а не
  // как имя малыша.
  if (!RegExp(r"^[\p{L}\p{M} '\-]+$", unicode: true).hasMatch(name)) {
    return PetNameError.badCharacters;
  }

  if (_looksRude(name)) return PetNameError.blocked;

  return null;
}

/// Грубое сито на устройстве.
///
/// Здесь нарочно мало корней — ровно самое очевидное на трёх языках КП.
/// Полный список живёт на сервере и правится модератором (КП 15.6): держать
/// его в приложении значит рассылать обновление ради каждого нового слова и
/// раздавать всем желающим готовый словарь брани.
bool _looksRude(String name) {
  final lower = name.toLowerCase();
  // Разрядка и подстановки — первое, что пробуют: «с у к а», «s-u-k-a».
  // Сравниваем со склеенным вариантом тоже.
  final packed = lower.replaceAll(RegExp(r"[\s'\-]"), '');

  for (final root in _rudeRoots) {
    if (lower.contains(root) || packed.contains(root)) return true;
  }
  return false;
}

/// Корни, а не слова целиком: приставки и окончания всё равно не перечислить.
const List<String> _rudeRoots = [
  // ru
  'хуй', 'хуе', 'пизд', 'ебан', 'ебат', 'бляд', 'сука', 'мудак', 'гандон',
  'пидор', 'пидар', 'залуп', 'дрочи',
  // en
  'fuck', 'shit', 'bitch', 'cunt', 'dick', 'asshole', 'bastard', 'whore',
  // zh
  '傻逼', '操你', '妈的', '混蛋', '贱人',
];
