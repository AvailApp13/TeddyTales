import 'package:flutter/material.dart';

import '../bear/bear_rig_spec.dart';

/// Разделы нижней навигации (КП 3.5).
///
/// КП говорит «шесть разделов», но не перечисляет их. На макете вкладок пять:
/// Главная · Комната · Магазин · Достижения · Профиль, причём «Достижения» —
/// механика сверх КП, отложенная во вторую версию. Оставшиеся четыре дополнены
/// двумя разделами, которым в КП нужен вход: обучение (раздел 9) и каталог
/// физических мишек (раздел 12).
///
/// **ДОПУЩЕНИЕ:** состав шестёрки выведен, а не задан. Уточнить.
///
/// ## Почему все разделы открыты с первого дня
///
/// Таблица КП 5 открывает комнату на третьей стадии, магазин на второй, а
/// обучение на четвёртой — то есть примерно на пятый день. Решением
/// заказчика (17.09) это изменено, и вот чем:
///
/// * КП 10.8 выдаёт двенадцать предметов бесплатно в первую секунду. Комната,
///   куда их ставить, при этом закрыта на три дня: подарок выдан и не
///   распаковывается.
/// * Обучение по КП 9.5 и 11.1 — главный источник монет. Закрытое до пятого
///   дня, оно оставляет магазин без покупателя: тратить нечего.
/// * Первый день решает, останется человек или нет, а занятий в нём при
///   закрытых разделах на пять минут.
///
/// Прогрессия из КП никуда не делась — она переехала внутрь разделов: в
/// обучении по стадиям открываются категории, в магазине подходящее возрасту
/// стоит первым. Закрытая дверь злит, витрина с «пока рано» — продаёт.
enum AppSection {
  home('Главная', Icons.home_rounded, BearStage.newborn),
  room('Обставить', Icons.auto_fix_high_rounded, BearStage.newborn),
  shop('Магазин', Icons.storefront_rounded, BearStage.newborn),
  learning('Обучение', Icons.school_rounded, BearStage.newborn),
  catalog('Мишки', Icons.card_giftcard_rounded, BearStage.newborn),
  profile('Профиль', Icons.person_rounded, BearStage.newborn);

  const AppSection(this.title, this.icon, this.minStage);

  /// Русское название — только для дев-целей (логи, отладочная панель).
  /// UI обязан брать подпись из `lib/l10n/sections_l10n.dart::sectionTitle`.
  final String title;
  final IconData icon;

  /// С какой стадии раздел открыт. До неё показывается замок с пояснением
  /// (КП 3.5).
  ///
  /// Сейчас все разделы открыты с рождения — почему, сказано выше. Механизм
  /// замка оставлен намеренно: по КП 15.4 тайминги настраиваются с сервера, и
  /// эти значения должны приезжать оттуда, а не стоять в коде. Пока стоят
  /// здесь как значения по умолчанию.
  final BearStage minStage;

  bool isUnlockedAt(BearStage stage) => stage.riveValue >= minStage.riveValue;

  /// Пояснение к замку — только для дев-целей. UI обязан брать текст из
  /// `lib/l10n/sections_l10n.dart::sectionLockReason`.
  String lockReason() => 'Откроется на стадии «${minStage.title}»';
}
