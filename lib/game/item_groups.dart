/// Подкатегории каталога: что это за вещь и какого она размера.
///
/// ## Зачем
///
/// Заказчик 21.09: «нужно сделать разделение в декоре — открываешь декор, а
/// ниже подкатегория „ковёр“. И сразу закладывай туда размер, фиксируй его:
/// последующие добавленные ковры должны быть ровно такого же размера, чтобы
/// они ложились всегда и мы их каждый раз не подгоняли. Я тебе его
/// отправляю, ты понимаешь, что это ковёр, и делаешь его не огромным, а тем,
/// который сейчас задан».
///
/// То есть размер — свойство не вещи, а её рода. Ковёр есть ковёр: он лежит
/// посреди комнаты, от центра во все стороны, и второй ковёр обязан лечь
/// ровно так же, иначе комната при каждой замене перестраивается на глаз.
///
/// Отсюда устройство: у каждой вещи каталога есть подкатегория, а размер и
/// повадку («стоит / лежит / висит») задаёт она. Новая картинка от заказчика
/// — это одна строка в каталоге с нужной подкатегорией, и вещь сразу встаёт
/// в комнату правильного размера. Подгонять больше нечего.
///
/// ## Исключения
///
/// [ItemMetrics] разрешает вещи иметь свой размер — но это именно
/// исключение, и каждое объяснено на месте. Ковров это не касается вовсе:
/// они всегда ровно [ItemGroup.rugs] и ничего своего не имеют, что и
/// проверяет `test/item_metrics_test.dart`.
///
/// ## Размеры
///
/// Всё в метрах и по ширине вещи: высоту даёт пропорция самой картинки
/// (см. `item_metrics.dart`). Числа те же, по которым собрана детская —
/// сверены с фоном, который заказчик прислал уже обставленным.
library;

import 'item_metrics.dart';

/// Род вещи: ковры, картины, кресла и так далее.
enum ItemGroup {
  // --- Мебель --------------------------------------------------------------
  //
  // Дробно: заказчик 21.09 просил развести роды вещей до конца — «отдельно
  // кресло и так далее». Кресло и стул сидят по-разному и занимают разное
  // место; комод и шкаф — тоже.
  beds('Кроватки', ItemFit.floor, 1.30),
  chairs('Кресла', ItemFit.floor, 0.88),
  seats('Стулья', ItemFit.floor, 0.40),
  dressers('Комоды', ItemFit.floor, 1.20),
  wardrobes('Шкафы', ItemFit.floor, 1.10),
  tables('Столики', ItemFit.floor, 0.50),
  baskets('Корзины для игрушек', ItemFit.floor, 0.45),
  shelves('Настенные полки', ItemFit.wall, 0.85),
  lamps('Светильники', ItemFit.floor, 0.35),

  // --- Декор ---------------------------------------------------------------
  //
  // Ковёр лежит у самых ног, в самом крупном месте кадра. Заказчик 21.09
  // попросил убавить десятую часть — отсюда 0.945 вместо метра.
  rugs('Ковры', ItemFit.rug, 0.945),
  pictures('Картины', ItemFit.wall, 0.55),
  clocks('Часы', ItemFit.wall, 0.30),
  garlands('Гирлянды', ItemFit.wall, 2.00),
  plants('Растения', ItemFit.floor, 0.45),
  flowers('Цветы', ItemFit.floor, 0.30),
  pillows('Подушки', ItemFit.floor, 0.45),
  // Обои и полы — не предметы, а поверхности: их не ставят, ими меняют
  // комнату. Размера у них нет.
  walls('Обои', null, null),
  floors('Полы', null, null),

  // --- Игрушки -------------------------------------------------------------
  plush('Мягкие игрушки', ItemFit.floor, 0.35),
  houses('Домики', ItemFit.floor, 0.66),
  toys('Игрушки', ItemFit.floor, 0.30),

  // --- Одежда --------------------------------------------------------------
  //
  // Надевается на мишку, а не ставится в комнату: размер ей задаёт риг.
  outfits('Комплекты', null, null),
  tops('Верх', null, null),
  bottoms('Низ', null, null),
  hats('Головные уборы', null, null),
  shoes('Обувь', null, null),
  extras('Аксессуары', null, null);

  const ItemGroup(this.title, this.fit, this.metres);

  /// Русское название — эталонное. На экране показывается перевод
  /// (`shopGroupName` в `lib/l10n/catalog_l10n.dart`).
  final String title;

  /// Как вещи этого рода держатся в комнате. `null` — в комнату не ставятся
  /// вовсе: обои, полы, одежда.
  final ItemFit? fit;

  /// Ширина вещи этого рода в метрах. `null` — размера нет, см. [fit].
  final double? metres;

  /// Ставится ли что-то этого рода в комнату.
  bool get placeable => fit != null;
}
