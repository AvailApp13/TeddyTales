import 'package:flutter_test/flutter_test.dart';
import 'package:teddy_tales/game/shop_items.dart';

/// Вещи показываются картинками, а не эмодзи (решение заказчика 20.09).
///
/// «Все эмодзи, которые остались, удали их». Эмодзи были заглушкой из
/// прототипа: 🛏 вместо кроватки, 🚪 вместо шкафа. Рядом с фотографическими
/// комнатами витрина с ними читалась как чужая игра.
void main() {
  group('Каталог', () {
    test('у вещи есть картинка или её нет — третьего не дано', () {
      // Путь картинки выводится из id, а не хранится отдельно: два
      // источника правды разъехались бы при первом переименовании.
      for (final item in ItemCatalog.all) {
        expect(
          item.image,
          item.photo ? 'assets/shop/items/${item.id}.webp' : isNull,
          reason: item.id,
        );
      }
    });

    test('картинки есть у большей части обстановки', () {
      // Присланного заказчиком набора хватило на мебель, декор и игрушки;
      // одежды в нём не было. Если однажды картинки пропадут из сборки,
      // магазин опустеет — тест скажет об этом раньше заказчика.
      final pictured = ItemCatalog.all.where((i) => i.photo).length;

      expect(pictured, greaterThanOrEqualTo(30));
    });
  });
}
